#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const htmlPath = path.join(__dirname, 'index.html');

const html = fs.readFileSync(htmlPath, 'utf8');

const results = [];
let failures = 0;

function check(name, pass, detail = '') {
  results.push({ name, pass, detail });
  if (!pass) {
    failures++;
    console.error(`FAIL: ${name}${detail ? ` — ${detail}` : ''}`);
  } else {
    console.log(`PASS: ${name}`);
  }
}

// 1. Single-file self-contained / zero external HTTP or script/link dependencies
check(
  'No external <script src=...>',
  !/<script\b[^>]*\bsrc\s*=/i.test(html),
  'Found external <script src=...>'
);
check(
  'No external <link href="http...">',
  !/<link\b[^>]*\bhref\s*=\s*["']https?:/i.test(html),
  'Found external HTTP <link>'
);
check(
  'No external <img src="http...">',
  !/<img\b[^>]*\bsrc\s*=\s*["']https?:/i.test(html),
  'Found external HTTP <img>'
);
check(
  'No external CSS @import url(http...)',
  !/@import\s+url\(\s*["']?https?:/i.test(html),
  'Found external CSS @import'
);

// 2. Inline <script> compiles without JS syntax errors
const scriptMatches = [...html.matchAll(/<script\b(?![^>]*\btype\s*=\s*["']application\/json["'])[^>]*>([\s\S]*?)<\/script>/gi)];
check('Has inline <script> block', scriptMatches.length >= 1, `Found ${scriptMatches.length}`);

scriptMatches.forEach((m, idx) => {
  const code = m[1];
  let compiled = false;
  let errMsg = '';
  try {
    new Function(code);
    compiled = true;
  } catch (err) {
    errMsg = err && err.message ? err.message : String(err);
  }
  check(`Inline script #${idx + 1} compiles cleanly`, compiled, errMsg);
});

// 3. Design tokens & isolated localStorage key aligned with prototype/current.html
check('Contains design token --bg:#FAFAF8', /--bg:\s*#FAFAF8\b/i.test(html));
check('Contains bottom padding token --page-pad-b:48px', /--page-pad-b:\s*48px\b/i.test(html));
check('Contains isolated storage key rc-watch-proto-v1', html.includes('rc-watch-proto-v1'));

// 4. Required data-testid anchors (static attributes)
const staticTestIds = [
  'view-mode-seg',
  'watch-capsule',
  'phone-dyn-island',
  'phone-refresh-btn',
  'phone-record-toggle',
  'phone-mark-btn',
  'phone-flush-btn',
  'watch-screen-tabs',
  'watch-record-toggle',
  'watch-mark-btn',
  'watch-queue-entry',
  'watch-flush-btn',
  'sim-rotate-60s',
  'sim-interruption',
  'sim-low-disk',
  'sim-mic-denied',
  'proto-reset',
  'comp-circular',
  'comp-corner',
  'comp-rectangular',
  'comp-inline',
];

for (const id of staticTestIds) {
  const re = new RegExp(`data-testid=["']${id}["']`);
  check(`Contains data-testid="${id}"`, re.test(html));
}

// 5. Dynamic slice data-testid prefixes generated by render script
const dynamicTestIdPrefixes = [
  'received-slice-',
  'play-slice-',
  'export-slice-',
  'delete-slice-',
];

for (const prefix of dynamicTestIdPrefixes) {
  check(
    `Contains dynamic data-testid prefix "${prefix}"`,
    html.includes(`data-testid="${prefix}`) || html.includes(`data-testid='${prefix}`)
  );
}

// 6. Check for duplicate static element IDs in HTML markup (outside <script> / <style>)
const markupOnly = html
  .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '')
  .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, '');
const idCounts = new Map();
for (const m of markupOnly.matchAll(/\bid\s*=\s*["']([^"']+)["']/g)) {
  const id = m[1];
  idCounts.set(id, (idCounts.get(id) || 0) + 1);
}
const dupIds = [...idCounts.entries()].filter(([, c]) => c > 1).map(([id, c]) => `${id}(${c})`);
check('No duplicate static id attributes in HTML', dupIds.length === 0, dupIds.join(', '));

console.log(`\nSummary: ${results.length - failures}/${results.length} checks passed.`);
if (failures > 0) {
  process.exit(1);
}
